// Posts: breadcrumb trail (visible + JSON-LD) and articleSection
// ---------------------------------------------------------------------------
const CRUMB_RE = /\n?<!-- blog-crumb:start -->[\s\S]*?<!-- blog-crumb:end -->/;
function updatePost(p) {
  const T = TAX.topics[p.topic];
  const url = `${SITE}/blog/${p.slug}`;
  let html = p.html;
  // JSON-LD
  let sawCrumb = false, sawArticle = false;
  html = html.replace(/(<script type="application\/ld\+json">)([\s\S]*?)(<\/script>)/g, (m, open, body, close) => {
    let d;
    try { d = JSON.parse(body); } catch { warnings.push(`${p.slug}: unparseable JSON-LD left untouched`); return m; }
    if (d['@type'] === 'BreadcrumbList') {
      sawCrumb = true;
      const last = d.itemListElement?.[d.itemListElement.length - 1];
      d = crumbLd([['Home', `${SITE}/`], ['Blog', `${SITE}/blog/`], [T.name, `${SITE}${topicUrl(p.topic)}`], [plain(last?.name || p.title), url]]);
    } else if (['Article', 'BlogPosting', 'NewsArticle'].includes(d['@type'])) {
      sawArticle = true;
      if (d.articleSection === T.name) return m;
      d.articleSection = T.name;
    } else return m;
    return `${open}\n    ${JSON.stringify(d)}\n    ${close}`;
  });
  if (!sawArticle) warnings.push(`${p.slug}: no Article schema found`);
  if (!sawCrumb) html = html.replace('</head>', `${ld(crumbLd([['Home', `${SITE}/`], ['Blog', `${SITE}/blog/`], [T.name, `${SITE}${topicUrl(p.topic)}`], [plain(p.title), url]]))}\n</head>`);
  // Visible trail under the top nav
  const cl = 'color:rgba(232,237,245,0.72);text-decoration:none;';
  const awardLinks = p.awards[0] === 'all' ? '' : ` <span style="margin:0 4px;">&middot;</span> ${p.awards.map((a) => `<a href="${guideUrl(a)}#articles" style="${cl}">${esc(TAX.awards[a].name)}</a>`).join(' &amp; ')}`;
  const crumb = `\n<!-- blog-crumb:start --><nav aria-label="Breadcrumb" style="max-width:780px;margin:0 auto;padding:16px 24px 0;font-family:'Outfit',sans-serif;font-size:14px;color:rgba(232,237,245,0.5);line-height:1.6;"><a href="/blog/" style="${cl}">Blog</a> <span style="margin:0 4px;">&rsaquo;</span> <a href="${topicUrl(p.topic)}" style="${cl}">${esc(T.name)}</a>${awardLinks}</nav><!-- blog-crumb:end -->`;
  html = html.replace(CRUMB_RE, '');
  const navEnd = html.indexOf('</nav>');
  if (navEnd === -1) { warnings.push(`${p.slug}: no top nav, visible breadcrumb not added`); }
  else html = html.slice(0, navEnd + 6) + crumb + html.slice(navEnd + 6);
  if (html !== p.html) { write(`blog/${p.slug}.html`, html); return 1; }
  return 0;
}

