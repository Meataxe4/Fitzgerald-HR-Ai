const BLOCK_RE = /<!-- blog-articles:start[\s\S]*?<!-- blog-articles:end -->/;
function injectGuide(award) {
  const rel = `${award}-award-guide.html`;
  let html = read(rel);
  const block = awardArticlesBlock(award);
  if (BLOCK_RE.test(html)) html = html.replace(BLOCK_RE, block);
  else {
    const anchor = '    <h2>Frequently Asked Questions</h2>';
    if (!html.includes(anchor)) { warnings.push(`${rel}: FAQ heading not found, articles block not added`); return; }
    html = html.replace(anchor, `    ${block}\n\n${anchor}`);
  }
  write(rel, html);
}

