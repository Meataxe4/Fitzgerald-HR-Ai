#!/usr/bin/env node
// Blog structure generator (Nov 2026 restructure, "Option B").
//
// One taxonomy (scripts/blog-taxonomy.json): every post has exactly one topic,
// one or more awards ("all" = any award) and one type. From it this script builds:
//
//   blog/index.html                 short front page: featured, topics, awards, latest, A-Z list
//   blog/topics/<topic>.html        one hub per topic
//   every blog/<post>.html          breadcrumb trail (visible + JSON-LD) and articleSection
//   hospitality- and restaurant-award-guide.html   "All <Award> Articles" block
//   (the five generated guides get the same block from build-vertical-pages.mjs)
//
// Post URLs never change. To add a post: write blog/<slug>.html, add it to the
// taxonomy JSON, add its netlify.toml rewrite and sitemap entry, then run
//   node scripts/build-blog-hubs.mjs
import fs from 'fs';
import path from 'path';
