const ROOT = path.join(__dirname, '..');
const BLOG = path.join(ROOT, 'blog');
const SITE = 'https://fitzhr.com';
const read = (rel) => fs.readFileSync(path.join(ROOT, rel), 'utf8');
const write = (rel, s) => { fs.mkdirSync(path.dirname(path.join(ROOT, rel)), { recursive: true }); fs.writeFileSync(path.join(ROOT, rel), s); };
const warnings = [];

// ---------------------------------------------------------------------------
// Load posts: taxonomy entry + dates read from the post file itself
// ---------------------------------------------------------------------------
const sitemap = read('sitemap.xml');
const lastmod = (url) => (sitemap.match(new RegExp(`<loc>${url.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}</loc>\\s*<lastmod>([^<]+)`)) || [])[1];
const files = fs.readdirSync(BLOG).filter((f) => f.endsWith('.html') && f !== 'index.html').map((f) => f.slice(0, -5)).sort();
for (const f of files) if (!TAX.posts[f]) throw new Error(`blog/${f}.html is not in scripts/blog-taxonomy.json`);
for (const s of Object.keys(TAX.posts)) if (!files.includes(s)) throw new Error(`taxonomy lists ${s} but blog/${s}.html does not exist`);

const POSTS = files.map((slug) => {
  const t = TAX.posts[slug];
  if (!TAX.topics[t.topic]) throw new Error(`${slug}: unknown topic ${t.topic}`);
  for (const a of t.awards) if (a !== 'all' && !TAX.awards[a]) throw new Error(`${slug}: unknown award ${a}`);
  const html = read(`blog/${slug}.html`);
  const date = (html.match(/"dateModified"\s*:\s*"(\d{4}-\d{2}-\d{2})/) || html.match(/"datePublished"\s*:\s*"(\d{4}-\d{2}-\d{2})/) || [])[1] || lastmod(`${SITE}/blog/${slug}`) || null;
  return { slug, ...t, date, html };
});
const bySlug = Object.fromEntries(POSTS.map((p) => [p.slug, p]));
const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
const fmtDate = (iso) => (iso ? `${Number(iso.slice(8, 10))} ${MONTHS[Number(iso.slice(5, 7)) - 1]} ${iso.slice(0, 4)}` : '');
const awardText = (p) => (p.awards[0] === 'all' ? 'All awards' : p.awards.map((a) => TAX.awards[a].name).join(' & '));
const topicUrl = (t) => `/blog/topics/${t}`;
const guideUrl = (a) => `/${a}-award-guide`;
const inTopic = (t) => POSTS.filter((p) => p.topic === t);
const inAward = (a) => POSTS.filter((p) => p.awards.includes(a));

